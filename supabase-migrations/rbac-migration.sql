-- Create role_permissions table
create table if not exists public.role_permissions (
  id bigint generated by default as identity not null,
  doc_id text not null, -- Format: DEPARTMENT_ROLE (e.g., "IT_MEMBER", "SALES_MANAGER")
  department text null,
  role text null,
  services jsonb not null default '{}'::jsonb,
  nav jsonb not null default '{}'::jsonb,
  security jsonb not null default '{}'::jsonb,
  account jsonb not null default '{}'::jsonb,
  dashboard jsonb not null default '{}'::jsonb,
  is_dashboard_allowed boolean null default true,
  updated_at timestamp with time zone null default now(),
  updated_by text null,
  constraint role_permissions_pkey primary key (id),
  constraint role_permissions_doc_id_key unique (doc_id)
) TABLESPACE pg_default;

create index if not exists idx_role_permissions_doc_id on public.role_permissions using btree (doc_id) TABLESPACE pg_default;
create index if not exists idx_role_permissions_department on public.role_permissions using btree (department) TABLESPACE pg_default;
create index if not exists idx_role_permissions_role on public.role_permissions using btree (role) TABLESPACE pg_default;

-- Create department_configs table
create table if not exists public.department_configs (
  id bigint generated by default as identity not null,
  name text null,
  roles jsonb null default '[]'::jsonb,
  color text null,
  deleted boolean null default false,
  created_at timestamp with time zone null default now(),
  updated_at timestamp with time zone null default now(),
  constraint department_configs_pkey primary key (id)
) TABLESPACE pg_default;

create index if not exists idx_department_configs_name on public.department_configs using btree (name) TABLESPACE pg_default;
create index if not exists idx_department_configs_deleted on public.department_configs using btree (deleted) TABLESPACE pg_default where (deleted is not null);

-- Enable Row Level Security (RLS)
alter table public.role_permissions enable row level security;
alter table public.department_configs enable row level security;

-- Create policies for role_permissions
create policy "Enable read access for all authenticated users" on public.role_permissions for select using (auth.role() = 'authenticated');
create policy "Enable insert for all authenticated users" on public.role_permissions for insert with check (auth.role() = 'authenticated');
create policy "Enable update for all authenticated users" on public.role_permissions for update using (auth.role() = 'authenticated');
create policy "Enable delete for all authenticated users" on public.role_permissions for delete using (auth.role() = 'authenticated');

-- Create policies for department_configs
create policy "Enable read access for all authenticated users" on public.department_configs for select using (auth.role() = 'authenticated');
create policy "Enable insert for all authenticated users" on public.department_configs for insert with check (auth.role() = 'authenticated');
create policy "Enable update for all authenticated users" on public.department_configs for update using (auth.role() = 'authenticated');
create policy "Enable delete for all authenticated users" on public.department_configs for delete using (auth.role() = 'authenticated');

